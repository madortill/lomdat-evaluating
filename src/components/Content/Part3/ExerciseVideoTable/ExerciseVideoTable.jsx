const ExerciseVideoTable = ({
    exerciseId = "discussion",
    title,
    instruction,
    videoSrc = "",
    posterSrc = "",
    videoTitle
}) => {
    const data = exerciseData[exerciseId] || exerciseData.discussion;

    const resolvedTitle = title || data.title;
    const resolvedInstruction = instruction || data.instruction;
    const resolvedVideoTitle = videoTitle || data.videoTitle;

    const [activeCategoryId, setActiveCategoryId] = useState(data.categories[0].id);
    const [expandedPanel, setExpandedPanel] = useState(null);

    const activeCategory = useMemo(() => {
        return data.categories.find((category) => category.id === activeCategoryId) || data.categories[0];
    }, [activeCategoryId, data.categories]);

    const tableRows = useMemo(() => {
        const rowsCount = Math.max(activeCategory.high.length, activeCategory.low.length);

        return Array.from({ length: rowsCount }, (_, index) => ({
            high: activeCategory.high[index] || "",
            low: activeCategory.low[index] || ""
        }));
    }, [activeCategory]);

    const toggleTableExpanded = () => {
        setExpandedPanel((prev) => (prev === "table" ? null : "table"));
    };

    const renderVideo = () => (
        <div className={styles.videoBox}>
            {videoSrc ? (
                <video
                    className={styles.video}
                    controls
                    poster={posterSrc}
                >
                    <source src={videoSrc} />
                </video>
            ) : (
                <div className={styles.videoPlaceholder}>
                    <span className={styles.playIcon}>▶</span>
                    <p>{resolvedVideoTitle}</p>
                </div>
            )}
        </div>
    );

    const renderTable = (isExpanded = false) => (
        <div className={`${styles.tablePanel} ${isExpanded ? styles.expandedTablePanel : ""}`}>
            <div className={styles.tabs}>
                {data.categories.map((category) => (
                    <button
                        key={category.id}
                        type="button"
                        className={`${styles.tabBtn} ${activeCategoryId === category.id ? styles.activeTab : ""}`}
                        onClick={() => setActiveCategoryId(category.id)}
                    >
                        {category.label}
                    </button>
                ))}
            </div>

            <div className={styles.tableCard}>
                <h2>{activeCategory.title}</h2>

                <div className={styles.tableContent}>
                    <div className={styles.tableHeader}>
                        <h3 className={styles.highHeader}>{activeCategory.highTitle}</h3>
                        <h3 className={styles.lowHeader}>{activeCategory.lowTitle}</h3>
                    </div>

                    <div className={styles.tableRows}>
                        {tableRows.map((row, index) => (
                            <div key={index} className={styles.tableRow}>
                                <div className={`${styles.tableCell} ${styles.highCell}`}>
                                    {row.high && <p>{row.high}</p>}
                                </div>

                                <div className={`${styles.tableCell} ${styles.lowCell}`}>
                                    {row.low && <p>{row.low}</p>}
                                </div>
                            </div>
                        ))}
                    </div>
                </div>
            </div>

            <button
                type="button"
                className={`${styles.tableExpandBtn} ${isExpanded ? styles.tableCollapseBtn : ""}`}
                onClick={toggleTableExpanded}
                aria-label={isExpanded ? "סגירת הטבלה" : "הגדלת הטבלה"}
            >
                ⛶
            </button>
        </div>
    );

    return (
        <section className={styles.page} dir="rtl">
            <h1 className={styles.title}>{resolvedTitle}</h1>

            <p className={styles.instruction}>{resolvedInstruction}</p>

            <div className={styles.mainContent}>
                {renderTable()}
                {renderVideo()}
            </div>

            {expandedPanel === "table" && (
                <div className={styles.fullscreenOverlay}>
                    <div className={styles.fullscreenTableWrapper}>
                        {renderTable(true)}
                    </div>
                </div>
            )}
        </section>
    );
};

export default ExerciseVideoTable;